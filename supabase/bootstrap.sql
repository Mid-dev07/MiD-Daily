-- 8) Planner modes + Finance budgets
alter table public.schedule_items
  add column if not exists activity_mode text not null default 'ONE_TIME',
  add column if not exists target_count integer,
  add column if not exists target_period text,
  add column if not exists duration_minutes integer,
  add column if not exists preferred_start_time time,
  add column if not exists preferred_end_time time,
  add column if not exists activity_deadline date;

update public.schedule_items
set activity_mode = case
  when coalesce(recurrence->>'frequency', 'NONE') <> 'NONE' then 'FIXED'
  else 'ONE_TIME'
end
where activity_mode = 'ONE_TIME';

alter table public.schedule_items
  drop constraint if exists schedule_items_check,
  drop constraint if exists schedule_items_end_time_check,
  drop constraint if exists schedule_items_activity_mode_check,
  drop constraint if exists schedule_items_flexible_target_check,
  drop constraint if exists schedule_items_preferred_time_check,
  drop constraint if exists schedule_items_deadline_check;

alter table public.schedule_items
  add constraint schedule_items_activity_mode_check
    check (activity_mode in ('FIXED','FLEXIBLE','ONE_TIME')),
  add constraint schedule_items_flexible_target_check
    check (
      activity_mode <> 'FLEXIBLE'
      or (
        target_count between 1 and 100
        and target_period in ('DAY','WEEK','MONTH')
        and duration_minutes between 5 and 1440
      )
    ),
  add constraint schedule_items_preferred_time_check
    check (
      (preferred_start_time is null and preferred_end_time is null)
      or (
        preferred_start_time is not null
        and preferred_end_time is not null
        and preferred_end_time > preferred_start_time
      )
    ),
  add constraint schedule_items_deadline_check
    check (activity_deadline is null or activity_deadline >= event_date);

alter table public.schedule_items
  alter column start_time drop not null,
  alter column end_time drop not null;

alter table public.schedule_items
  add constraint schedule_items_end_time_check
    check (
      (activity_mode = 'FLEXIBLE' and start_time is null and end_time is null)
      or
      (activity_mode <> 'FLEXIBLE' and start_time is not null and end_time is not null and end_time > start_time)
    );

create index if not exists schedule_items_user_mode_date_idx
  on public.schedule_items (user_id, activity_mode, event_date);

